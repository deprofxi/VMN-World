#!/usr/bin/env node
/**
 * Bootstrap environment variables with safe defaults and cryptographically
 * random credentials for all-in-one Docker Compose & Coolify deployments.
 *
 * Usage:
 *   node scripts/bootstrap-env.mjs [--file .env]
 *   node scripts/bootstrap-env.mjs --coolify
 *   node scripts/bootstrap-env.mjs --print
 *
 * Existing keys in the target (.env file or Coolify resource) are never
 * overwritten, making this script safe and idempotent across redeployments.
 */

import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const hex = (bytes) => randomBytes(bytes).toString("hex");

function buildDefaults() {
  const pgUser = process.env.POSTGRES_USER || "vmn_user";
  const pgPassword = process.env.POSTGRES_PASSWORD || hex(24);
  const pgDb = process.env.POSTGRES_DB || "vmn_enterprise";
  const pgHost = process.env.POSTGRES_HOST || "postgres";
  const pgPort = process.env.POSTGRES_PORT || "5432";

  const redisPassword = process.env.REDIS_PASSWORD || hex(24);
  const redisHost = process.env.REDIS_HOST || "redis";
  const redisPort = process.env.REDIS_PORT || "6379";

  return {
    NODE_ENV: "production",
    PORT: "5500",
    APP_NAME: "VMN World",
    AUTO_MIGRATE: "true",
    AUTO_SEED: "false",

    // PostgreSQL
    POSTGRES_USER: pgUser,
    POSTGRES_PASSWORD: pgPassword,
    POSTGRES_DB: pgDb,
    POSTGRES_HOST: pgHost,
    POSTGRES_PORT: pgPort,
    DATABASE_URL: `postgresql://${pgUser}:${pgPassword}@${pgHost}:${pgPort}/${pgDb}?schema=public`,

    // Redis
    REDIS_HOST: redisHost,
    REDIS_PORT: redisPort,
    REDIS_PASSWORD: redisPassword,
    REDIS_URL: `redis://:${redisPassword}@${redisHost}:${redisPort}`,

    // Storage (local by default; credentials generated for optional MinIO/S3 service)
    STORAGE_DRIVER: "local",
    STORAGE_ENDPOINT: "http://minio:9000",
    STORAGE_BUCKET: "vmnl-assets",
    STORAGE_REGION: "us-east-1",
    STORAGE_ACCESS_KEY: `vmnl_${hex(8)}`,
    STORAGE_SECRET_KEY: hex(24),

    // Security & Auth Secrets
    JWT_SECRET: hex(32),
    SESSION_SECRET: hex(32),
    PII_ENCRYPTION_KEY: hex(32),
    FUSION_EVENTS_HMAC_SECRET: hex(24),

    // Federation
    AZEEBO_CLIENT_ID: "vmnl_enterprise_hub",
    AZEEBO_WEBHOOK_SECRET: hex(24),
    AZEEBO_FEDERATION_SECRET: hex(24),
  };
}

function parseEnvFile(content) {
  const map = new Map();
  for (const rawLine of content.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    const eq = line.indexOf("=");
    if (eq === -1) continue;
    const key = line.slice(0, eq).trim();
    const val = line.slice(eq + 1).trim();
    if (key) map.set(key, val);
  }
  return map;
}

function syncEnvFile(filePath) {
  const target = resolve(process.cwd(), filePath);
  const existingContent = existsSync(target) ? readFileSync(target, "utf8") : "";
  const existing = parseEnvFile(existingContent);
  const defaults = buildDefaults();

  // Keep DATABASE_URL and REDIS_URL consistent with existing user/password/db if already set
  if (existing.has("POSTGRES_USER") || existing.has("POSTGRES_PASSWORD") || existing.has("POSTGRES_DB")) {
    const u = existing.get("POSTGRES_USER") || defaults.POSTGRES_USER;
    const p = existing.get("POSTGRES_PASSWORD") || defaults.POSTGRES_PASSWORD;
    const d = existing.get("POSTGRES_DB") || defaults.POSTGRES_DB;
    const h = existing.get("POSTGRES_HOST") || defaults.POSTGRES_HOST;
    const port = existing.get("POSTGRES_PORT") || defaults.POSTGRES_PORT;
    defaults.DATABASE_URL = `postgresql://${u}:${p}@${h}:${port}/${d}?schema=public`;
  }
  if (existing.has("REDIS_PASSWORD")) {
    const rp = existing.get("REDIS_PASSWORD");
    const rh = existing.get("REDIS_HOST") || defaults.REDIS_HOST;
    const rport = existing.get("REDIS_PORT") || defaults.REDIS_PORT;
    defaults.REDIS_URL = `redis://:${rp}@${rh}:${rport}`;
  }

  const added = [];
  for (const [key, value] of Object.entries(defaults)) {
    if (!existing.has(key) || existing.get(key) === "") {
      added.push(`${key}=${value}`);
    }
  }

  if (added.length === 0) {
    console.log(`[bootstrap-env] ${filePath} already contains all required variables.`);
    return;
  }

  const prefix = existingContent && !existingContent.endsWith("\n") ? "\n" : "";
  const header = existingContent ? `${prefix}# Auto-generated by scripts/bootstrap-env.mjs\n` : "# Auto-generated by scripts/bootstrap-env.mjs\n";
  writeFileSync(target, `${existingContent}${header}${added.join("\n")}\n`, { mode: 0o600 });
  console.log(`[bootstrap-env] Added ${added.length} variables to ${filePath}.`);
}

async function syncCoolify() {
  const apiUrl = (process.env.COOLIFY_API_URL || "").replace(/\/+$/, "");
  const token = process.env.COOLIFY_API_TOKEN || "";
  const uuid = process.env.COOLIFY_RESOURCE_UUID || "";
  const resourceType = process.env.COOLIFY_RESOURCE_TYPE || "applications";

  if (!apiUrl || !token || !uuid) {
    console.log("[bootstrap-env] COOLIFY_API_URL / COOLIFY_API_TOKEN / COOLIFY_RESOURCE_UUID not set; skipping Coolify env sync.");
    return;
  }

  const headers = {
    Authorization: `Bearer ${token}`,
    "Content-Type": "application/json",
    Accept: "application/json",
  };

  const listRes = await fetch(`${apiUrl}/api/v1/${resourceType}/${uuid}/envs`, { headers });
  if (!listRes.ok) {
    throw new Error(`Failed to fetch Coolify envs (${listRes.status}): ${await listRes.text()}`);
  }

  const existingList = await listRes.json();
  const existingMap = new Map(
    (Array.isArray(existingList) ? existingList : []).map((item) => [item.key, item.value]),
  );

  const defaults = buildDefaults();
  if (existingMap.has("POSTGRES_USER") || existingMap.has("POSTGRES_PASSWORD") || existingMap.has("POSTGRES_DB")) {
    const u = existingMap.get("POSTGRES_USER") || defaults.POSTGRES_USER;
    const p = existingMap.get("POSTGRES_PASSWORD") || defaults.POSTGRES_PASSWORD;
    const d = existingMap.get("POSTGRES_DB") || defaults.POSTGRES_DB;
    const h = existingMap.get("POSTGRES_HOST") || defaults.POSTGRES_HOST;
    const port = existingMap.get("POSTGRES_PORT") || defaults.POSTGRES_PORT;
    defaults.DATABASE_URL = `postgresql://${u}:${p}@${h}:${port}/${d}?schema=public`;
  }
  if (existingMap.has("REDIS_PASSWORD")) {
    const rp = existingMap.get("REDIS_PASSWORD");
    const rh = existingMap.get("REDIS_HOST") || defaults.REDIS_HOST;
    const rport = existingMap.get("REDIS_PORT") || defaults.REDIS_PORT;
    defaults.REDIS_URL = `redis://:${rp}@${rh}:${rport}`;
  }

  const data = Object.entries(defaults)
    .filter(([key]) => !existingMap.has(key) || !existingMap.get(key))
    .map(([key, value]) => ({
      key,
      value,
      is_preview: false,
      is_build_time: false,
      is_literal: true,
    }));

  if (data.length === 0) {
    console.log("[bootstrap-env] Coolify resource already has all required environment variables.");
    return;
  }

  const bulkRes = await fetch(`${apiUrl}/api/v1/${resourceType}/${uuid}/envs/bulk`, {
    method: "PATCH",
    headers,
    body: JSON.stringify({ data }),
  });

  if (!bulkRes.ok) {
    throw new Error(`Failed to sync Coolify envs (${bulkRes.status}): ${await bulkRes.text()}`);
  }

  console.log(`[bootstrap-env] Synced ${data.length} auto-generated variables to Coolify (${resourceType}/${uuid}).`);
}

const args = process.argv.slice(2);
if (args.includes("--coolify")) {
  await syncCoolify();
} else if (args.includes("--print")) {
  for (const [k, v] of Object.entries(buildDefaults())) {
    console.log(`${k}=${v}`);
  }
} else {
  const fileIdx = args.indexOf("--file");
  const filePath = fileIdx !== -1 && args[fileIdx + 1] ? args[fileIdx + 1] : ".env";
  syncEnvFile(filePath);
}
